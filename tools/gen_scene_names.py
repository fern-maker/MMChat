#!/usr/bin/env python3
"""Generates native/scene_names.h from the decomp's scene table.

Each DEFINE_SCENE line in mm-decomp/include/tables/scene_table.h is preceded by a
comment with the scene's readable name; this turns those into a lookup table.

Usage: python3 tools/gen_scene_names.py
"""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
TABLE = ROOT / "mm-decomp" / "include" / "tables" / "scene_table.h"
OUTPUT = ROOT / "native" / "scene_names.h"

# Friendlier names where the decomp comment is written for developers.
OVERRIDES = {
    0x08: "Cutscene",
    0x10: "Mama's House & Barn",
    0x30: "Dampe's House",
    0x62: "Great Bay (Cutscene)",
}

ENTRY = re.compile(r"/\*\s*0x([0-9A-Fa-f]+)\s*\*/\s*DEFINE_SCENE\(\s*\w+\s*,\s*(\w+)")


def main():
    names = {}
    comment = None
    for line in TABLE.read_text().splitlines():
        stripped = line.strip()
        if stripped.startswith("//"):
            comment = stripped[2:].strip()
            continue
        match = ENTRY.search(stripped)
        if match:
            index = int(match.group(1), 16)
            names[index] = OVERRIDES.get(index) or comment or match.group(2)
        comment = None

    count = max(names) + 1
    lines = [
        "// Generated by tools/gen_scene_names.py from mm-decomp/include/tables/scene_table.h. Do not edit.",
        "#ifndef MMCHAT_SCENE_NAMES_H",
        "#define MMCHAT_SCENE_NAMES_H",
        "",
        f"#define SCENE_NAME_COUNT {count}",
        "",
        "static const char* const scene_names[SCENE_NAME_COUNT] = {",
    ]
    for index in range(count):
        name = names.get(index)
        value = '"' + name.replace("\\", "\\\\").replace('"', '\\"') + '"' if name else "0"
        lines.append(f"    /* 0x{index:02X} */ {value},")
    lines += ["};", "", "#endif", ""]
    OUTPUT.write_text("\n".join(lines))
    print(f"Wrote {len(names)} scene names to {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
